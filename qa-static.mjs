import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./src/main.js',import.meta.url),'utf8');
const productEnd=source.indexOf('\n\nconst categories');
const artStart=source.indexOf('let artInstance = 0;');
const artEnd=source.indexOf('\nfunction productCard',artStart);
const escapeFn=`function escapeHtml(s=''){return String(s).replace(/[&<>\"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','\"':'&quot;',\"'\":'&#39;'}[c]));}`;
const ctx={};
vm.createContext(ctx);
vm.runInContext(source.slice(0,productEnd).replace(/^import .*?;\s*/, '')+'\n'+escapeFn+'\n'+source.slice(artStart,artEnd)+'\nglobalThis.productsOut=products; globalThis.artOut=artSvg;',ctx);
const products=ctx.productsOut;
const categories={Klavyeler:5,Mouse:4,Mousepad:3,Kulaklık:3,Aksesuarlar:3};
assert.equal(products.length,18,'18 models expected');
assert.equal(new Set(products.map(p=>p.id)).size,18,'unique product IDs');
for(const [category,count] of Object.entries(categories)) assert.equal(products.filter(p=>p.category===category).length,count,category+' count');
assert(products.every(p=>Number.isFinite(p.price)&&p.price>0),'all prices positive');
assert(products.every(p=>p.specs?.length>=4),'technical specs present');
assert(products.every(p=>p.art&&['keyboard','mouse','pad','headset','accessory'].includes(p.art)),'valid art category');
assert(products.filter(p=>p.oldPrice).every(p=>p.oldPrice>p.price),'sale prices exceed current prices');
const svgs=products.map(p=>ctx.artOut(p));
assert(svgs.every((s,i)=>s.includes(`aria-label="${products[i].name} ürün illüstrasyonu"`)),'accessible SVG labels');
assert.equal(new Set(svgs).size,18,'each SKU has unique vector artwork');
assert(svgs.every(s=>s.includes('<svg')&&s.includes('</svg>')),'SVG markup complete');
const css=fs.readFileSync(new URL('./src/style.css',import.meta.url),'utf8');
assert(css.includes('.product-modal>.modal-close{position:absolute;top:12px;right:12px;z-index:20'),'reliable modal close styling');
assert(source.includes("if((el.classList.contains('modal-backdrop') || el.classList.contains('drawer-backdrop')) && e.target !== el)return;"),'backdrop clicks do not intercept inner controls');
assert(!source.includes('onclick="event.stopPropagation()"'),'no inline event handler blocking cart actions');
assert(source.includes("if(e.key==='Escape')"),'Escape closes overlays');
assert(source.includes("page==='checkout' && !state.cart.length"),'empty checkout guarded');
assert(source.includes('Math.min(99,item.qty+Number(el.dataset.delta))'),'cart quantity capped');
assert(source.includes('function showBrandLoader(duration=520)'),'branded loader function exists');
assert(source.includes('showBrandLoader(900)'),'initial page loader enabled');
assert(source.includes('showBrandLoader(520)'),'route transition loader enabled');
assert(source.includes('function setupScrollReveal()'),'scroll reveal behavior exists');
assert(css.includes('.keyora-loader.is-visible'),'loader visible state styling exists');
assert(css.includes('.motion-ready .scroll-reveal:not(.is-revealed)'),'scroll reveal styles exist');
assert(css.includes('prefers-reduced-motion:reduce'),'reduced-motion preference supported');
const pkg=JSON.parse(fs.readFileSync(new URL('./package.json',import.meta.url),'utf8'));
assert(pkg.scripts.build.includes('vite build'),'build script configured');
console.log('STATIC QA PASS');
console.log(JSON.stringify({productCount:products.length,categoryCounts:categories,uniqueVectorArt:new Set(svgs).size,uniqueProductIds:new Set(products.map(p=>p.id)).size,checks:28},null,2));
